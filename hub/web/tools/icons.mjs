// copies the shared icon set (assets/icons/*.svg, 24×24, stroke currentColor) into the
// web app as hub/web/iconset.js, so the page needs no fetches for its icons and works
// offline and from a static server. Run it after the icons change:
//   node hub/web/tools/icons.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const dir = join(root, 'assets/icons');
const out = join(root, 'hub/web/iconset.js');

const set = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, f), 'utf8');
  const m = svg.match(/^\s*<svg\b[^>]*viewBox="0 0 24 24"[^>]*>([\s\S]*)<\/svg>\s*$/);
  if (!m) throw new Error(`${f}: not a 24×24 icon`);
  // only shapes: nothing that could run or load
  const inner = m[1].trim();
  if (/<(script|foreignObject|image|use)\b|\bon\w+=|href=/i.test(inner)) throw new Error(`${f}: more than shapes`);
  set[f.slice(0, -4)] = inner;
}

const body = Object.entries(set)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  out,
  `// generated by hub/web/tools/icons.mjs from assets/icons/: don't edit, run that again\n// each is the inside of a 24×24 svg drawn with stroke="currentColor"\nexport default {\n${body}\n};\n`,
);
console.log(`${Object.keys(set).length} icons → ${out}`);
