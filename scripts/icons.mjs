// copies the shared icon set (assets/icons/*.svg, 24×24, stroke currentColor) into the
// hub's own pages as a sprite, hub/static/icons.svg (a <symbol id="i-name"> each, served at /static/icons.svg and
// drawn by the icon macro in hub/templates/icons.html). Run it after the icons change:
//   node scripts/icons.mjs
// (the app embeds assets/icons itself: app/src/icons.rs)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/icons');
const sprite = join(root, 'hub/static/icons.svg');

const set = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, f), 'utf8');
  const m = svg.match(/^\s*<svg\b[^>]*viewBox="0 0 24 24"[^>]*>([\s\S]*)<\/svg>\s*$/);
  if (!m) throw new Error(`${f}: not a 24×24 icon`);
  // only shapes: nothing that could run or load
  const inner = m[1].trim();
  if (/<(script|foreignObject|image|use)\b|\bon\w+=|href=/i.test(inner)) throw new Error(`${f}: more than shapes`);
  set[f.slice(0, -4)] = inner;
}

// the symbols carry no fill or stroke of their own: a <use> inherits them from the page's
// <svg class="icon" fill="none" stroke="currentColor" …>, which can fill one (a star)
const draw = 'viewBox="0 0 24 24"';
const symbols = Object.entries(set)
  .map(([k, v]) => `<symbol id="i-${k}" ${draw}>${v}</symbol>`)
  .join('\n');
writeFileSync(
  sprite,
  `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- generated by scripts/icons.mjs from assets/icons/: don't edit, run that again -->\n${symbols}\n</svg>\n`,
);
console.log(`${Object.keys(set).length} icons → ${sprite}`);
